CREATE TABLE piloto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(100) NOT NULL,
    keycloak_sub VARCHAR(64)  UNIQUE,
    activo       BOOLEAN      NOT NULL DEFAULT TRUE
);

-- tipo_vuelo_codigo es el código del tipo de vuelo (vive en vuelos_db, por eso sin FK)
CREATE TABLE certificacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    piloto_id         BIGINT      NOT NULL REFERENCES piloto(id),
    tipo_vuelo_codigo VARCHAR(50) NOT NULL,
    UNIQUE (piloto_id, tipo_vuelo_codigo)
);

-- reserva_id es referencia lógica a vuelos_db (sin FK)
CREATE TABLE asignacion (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    piloto_id  BIGINT    NOT NULL REFERENCES piloto(id),
    fecha_hora TIMESTAMP NOT NULL,
    reserva_id BIGINT    NOT NULL UNIQUE
);
CREATE INDEX idx_asignacion_piloto ON asignacion(piloto_id);
